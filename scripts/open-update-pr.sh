# Publish the dependency updates in the working tree as the single update PR.
# Always uses one fixed branch, force-pushed from the current checkout, and
# edits the open PR in place instead of opening another. Run after
# apply-updates.sh, from a checkout of main with git identity configured.
#
# Environment:
#   PR_BODY        PR description (default: empty)
#   UPDATE_BRANCH  branch name (default: chore/update-deps)

set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$PROJECT_ROOT"

BRANCH="${UPDATE_BRANCH:-chore/update-deps}"
NEW_VERSION=$(grep -oP '^version: \K[0-9.]+' socket-proxy/config.yaml)
TITLE="chore: bump dependencies to v${NEW_VERSION}"

# Restarting the branch from the current checkout each run is what keeps the
# PR a single commit on top of main; the old branch tip is simply replaced.
git checkout -B "$BRANCH"
# GITHUB_TOKEN may never push changes under .github/workflows/ -- the remote
# rejects the push outright. Any base image or action version bump that lands
# in ci.yaml has to be applied by hand.
git add socket-proxy/Dockerfile socket-proxy/build.yaml socket-proxy/config.yaml \
        socket-proxy/CHANGELOG.md \
        socket-proxy/rootfs/etc/services.d/socket-proxy/run \
        Makefile tests/test_addon.sh AGENTS.md
git restore .github/workflows/ci.yaml 2>/dev/null || true
git commit -m "$TITLE"
git push --force origin "$BRANCH"

BODY="## Dependency update

${PR_BODY:-}

---
*Generated by the weekly update-deps workflow. Review the diff and merge when ready.*"

OPEN_PR=$(gh pr list --head "$BRANCH" --base main --state open --json number --jq '.[0].number // empty')
if [[ -n "$OPEN_PR" ]]; then
    gh pr edit "$OPEN_PR" --title "$TITLE" --body "$BODY"
else
    gh pr create --base main --head "$BRANCH" --title "$TITLE" --body "$BODY"
fi
